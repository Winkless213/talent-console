// 口径说明的正文。ds：数据集；x：示例数据，没有时为 null；sync：取数状态；h：小标题用哪一级（弹窗里上面有 h2 的标题，用 h3；直接放在页面上用 h2）
export function rulesDoc(ds, x, sync, h = 'h3') {
  const r = RULES, c = ds.meta.coverage, li = l => `<ul>${l.map(v => `<li>${v}</li>`).join('')}</ul>`, hd = t => `<${h}>${t}</${h}>`;
  return hd('数据从哪来') + li([...(sync.mock ? [`现在看到的是演示数据：一套假的企业微信接口按固定种子生成，接口路径和字段结构与官方接口一致，人名是「姓 + 数字」的占位名，时钟固定在 ${stamp(ds.meta.now)}。同一套取数和核算代码，接上真实的企业微信就是真实数据。`,
        '真实使用时，考勤和组织数据全部来自企业微信官方接口：通讯录、人事花名册、打卡规则和排班、打卡日报、今天的打卡记录、请假审批、往月月报。',
        '数据只放在内存里（演示时是这个浏览器标签页，真实使用时是本机服务），不存盘、不上传。打卡的位置、WiFi、设备信息不取。']
      : ['全部来自企业微信官方接口：通讯录、人事花名册、打卡规则和排班、打卡日报、今天的打卡记录、请假审批、往月月报。',
        '数据只放在这台电脑的内存里，不存盘、不上传；关掉命令行窗口就没有了。打卡的位置、WiFi、设备信息不取。',
        `每 ${Math.round(sync.every / 60)} 分钟自动取一次。今天的数来自实时打卡，昨天及以前用企业微信生成好的日报。`]),
      `现在覆盖 ${c.people} 人：固定班 ${c.rule.fixed}、排班 ${c.rule.shift}、自由上下班 ${c.rule.free}、没有打卡规则 ${c.rule.none}；日报从 ${c.dayFrom || '—'} 到 ${c.dayTo || '—'}。`])
    + hd('人员信息') + li(['部门取公司下面第一级，小组取本人所在最深一级。',
      `主管先取企业微信里登记的直属上级（${c.leaderDirect} 人）；没登记的取所在部门的负责人（${c.leaderDept} 人）；都没有的留空（${c.leaderNone} 人）。`,
      `用工类型由花名册的「员工类型」和「员工状态」合成：员工类型不是全职的照原样显示（如实习），全职且在试用的算试用期，其余算正式工，花名册里没有的显示未登记。入职时间有 ${c.noJoin} 人没登记。`])
    + hd('今天') + li([`状态：正常在岗；迟到（已到岗，上班卡被企业微信判了迟到）；加班中（过了班次下班时间 ${Math.round(r.otMinSec / 60)} 分钟还没打下班卡）；已下班；未签到（过了上班时间加允许迟到的时间还没打卡）；未打卡（自由上下班的人，过了本人平时到岗时间 ${r1(r.freeWait / H)} 小时还没打卡）；未到上班时间；请假；休息；不考勤（没有打卡规则，或今天没有排班）。`,
      '合计的两个数：「在岗」是正常在岗、迟到、加班中三种状态的人加起来，这些人此刻都在岗位上；「未到岗」是未签到和未打卡的人加起来。',
      `自由上下班的人「平时到岗时间」取近 30 天上班卡时间的中间值，不足 5 天的按 ${hmOf(r.freeOn)} 算。`,
      '出勤率 = 实到 ÷ 应到。应到不含全天请假的人；今天的出勤率只算已经到上班时间的人，早上不会因为多数人还没到点而显得很低。'])
    + hd('昨天及以前') + li(['迟到、早退、缺卡、旷工都直接用企业微信日报里的判定，不重算。一天只打了一次卡的，企业微信没判异常也算缺卡。',
      '缺勤 = 企业微信判的旷工 + 该上班却没打卡也没请假的（自由上下班的人企业微信不判旷工，这里记成未打卡）。',
      '近7天、本月都只算到昨天，因为今天的日报企业微信还没生成。凌晨的卡按企业微信的换日时间归到前一天。',
      '表格里的「请假 n 次」是有请假记录的天数，不论当天请了几小时。'])
    + hd('工时和加班') + li(['工时用企业微信算好的「计入工时」（整小时）；在岗时长是当天第一次打卡到最后一次打卡。两个数都给，不拿在岗时长的长短评价人。',
      `加班：企业微信记了加班时长的，用它的；没记的，固定班和排班的人在工作日下班卡比班次下班时间晚满 ${Math.round(r.otMinSec / 60)} 分钟，算晚走加班。自由上下班没有班次，不算加班，只看在岗时长。数字后面标了「企微」或「晚走」。`,
      `近 31 天提交的加班审批：${c.otForms == null ? '没有取到' : c.otForms + ' 张'}；本月企业微信记有加班的 ${c.otWecomMonth} 人。`,
      '请假：昨天及以前用日报里挂的假勤记录；今天用已通过的请假审批，审批中的不算请假，只在提醒里标「请假待审批」。'])
    + hd('六个提醒') + li(AI.map(([key, t]) => `<b>${t}</b>：${aiRule(key, r)}。`))
    + hd('其它') + li(['「异常优先」排序：所选时段里没到的排最前，其次迟到、缺卡；长期性的提醒只在同一档里再分先后。',
      '法定节假日：只有打卡规则开了「同步法定节假日」的才按 2026 年放假安排算，2027 年的安排还没有加进去。',
      x ? '工作事项、业绩、能力评价、薪酬、培养、招聘是示例数据：企业微信里没有这些，演示时按固定种子生成，页面上都标了「示例」。接真实企业微信后，这些位置显示「待接入」，不放任何编出来的数。'
        : '还没有接入：工作情况、业绩与质量、个人能力、薪酬与人效、人才评价、培养和招聘。这些位置显示「待接入」或「—」，不放任何编出来的数。'])
    + (x ? hd('示例数据的口径') + li(demoRules().map(([t, v]) => `<b>${t}</b>：${v}。`)) : '');
}
