// 考勤的六个提醒：[信号, 名称, 图标, 色调]。门槛都在 core/model.js 的 RULES 里，这里只负责把门槛写成一句话
export const AI = [['att', '考勤异常', 'alarm', 'r'], ['freqLate', '频繁迟到', 'info', 'o'], ['long', '长期加班', 'info', 'o'], ['streak', '连续工作', 'target', 'b'], ['rest', '休息不足', 'target', 'r'], ['shift', '工时异常', 'target', 'b']];
export const aiRule = (k, R) => ({
  att: `今天迟到，或者到了上班时间还没有打卡（自由上下班的人：过了本人平时到岗时间 ${r1(R.freeWait / H)} 小时还没打卡）`,
  freqLate: `本月迟到满 ${R.freqLate} 次，今天迟到也算在内`,
  long: `近 ${R.longWindow} 天里有 ${R.longDays} 天在岗满 ${R.longHours} 小时`,
  streak: `连续 ${R.streakDays} 天及以上每天都有打卡`,
  rest: `昨天最后一次打卡到今天第一次打卡，间隔不足 ${R.restHours} 小时`,
  shift: `近 ${R.longWindow} 天的日均在岗时长，比再往前的日子高出或低出 ${R.shiftPct}% 及以上（两段各至少 ${R.shiftMinDays} 天有打卡）`
})[k];

